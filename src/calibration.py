"""
Phase D: Leakage-Safe Probability Calibration for Multiclass Emotion Recognition.

Guarantees:
- Calibration parameters (temperature T or Platt coefficients) are fitted strictly on
  out-of-fold decision scores generated across subject-disjoint inner splits on outer training subjects only.
- Held-out test subjects never contribute to calibration fitting, hyperparameter selection,
  scaling, or threshold selection.
- Output probabilities are non-negative, finite, sum to 1.0 within numerical precision,
  and preserve class alignment [0: neutral, 1: sad, 2: fear, 3: happy].
"""

