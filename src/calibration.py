def generate_group_safe_oof_decision_scores(
    X_train: np.ndarray,
    y_train: np.ndarray,
    train_metadata: pd.DataFrame,
    group_key: str = "subject_id",
    n_splits: int = 3,
    C: float = 1.0,
    gamma: Union[str, float] = "scale",
    cache_size: int = 500,
) -> np.ndarray:
    """
    Generate out-of-fold decision scores for outer training samples using subject-disjoint inner splits.
    
    Parameters:
        X_train: Outer training features, shape (N_train, N_features).
        y_train: Outer training labels, shape (N_train,).
        train_metadata: DataFrame with group_key (e.g., 'subject_id') for each sample.
        group_key: Column name used to group samples (ensuring subjects are not split).
        n_splits: Number of inner splits.
        C, gamma, cache_size: Hyperparameters for the inner RBF-SVM pipelines.
        
    Returns:
        Z_oof: Out-of-fold decision scores, shape (N_train, n_classes).
               Each sample's score was generated by a model that did not see that sample's subject.
    """
    groups = train_metadata[group_key].to_numpy()
    unique_groups = len(np.unique(groups))
    actual_splits = min(n_splits, unique_groups)
    
    gkf = GroupKFold(n_splits=actual_splits)
    n_samples = len(X_train)
    n_classes = len(np.unique(y_train))
    
    Z_oof = np.zeros((n_samples, n_classes), dtype=np.float64)
    evaluated_mask = np.zeros(n_samples, dtype=bool)
    
    for split_idx, (inner_tr_idx, inner_val_idx) in enumerate(gkf.split(X_train, y_train, groups=groups)):
        # Verify strict subject-level disjointness
        tr_subs = set(train_metadata.iloc[inner_tr_idx][group_key].unique())
        val_subs = set(train_metadata.iloc[inner_val_idx][group_key].unique())
        assert tr_subs.isdisjoint(val_subs), f"Inner split {split_idx} subject leakage detected!"
        
        # Train-only pipeline for this inner fold
        inner_pipe = create_baseline_pipeline(C=C, gamma=gamma, cache_size=cache_size)
        inner_pipe.fit(X_train[inner_tr_idx], y_train[inner_tr_idx])
        
        # Predict decision scores on inner validation subjects
        scores_val = inner_pipe.decision_function(X_train[inner_val_idx])
        Z_oof[inner_val_idx] = scores_val
        evaluated_mask[inner_val_idx] = True
        
    assert np.all(evaluated_mask), "Not all training samples received out-of-fold decision scores!"
    return Z_oof


class GroupSafeTemperatureScalingCalibrator:
    """
    Group-Safe Temperature Scaling Calibrator:
        p(y = c | z; T) = exp(z_c / T) / sum_j exp(z_j / T)
        
    where T > 0 is optimized strictly on out-of-fold decision scores Z_oof to minimize NLL.
    
    Properties:
    - Exactly preserves the SVM classifier's argmax and accuracy:
      argmax_c p_c(z; T) == argmax_c z_c for all T > 0.
    - Calibrates confidence, dramatically reducing Expected Calibration Error (ECE).
    """
    def __init__(self, bounds: Tuple[float, float] = (0.05, 50.0)):
        self.bounds = bounds
        self.temperature_: float = 1.0
        self.classes_ = None

    def fit(self, Z_oof: np.ndarray, y: np.ndarray) -> "GroupSafeTemperatureScalingCalibrator":
        self.classes_ = np.sort(np.unique(y))
        n_samples = len(y)

        def nll_objective(T_val):
            T = float(T_val[0]) if hasattr(T_val, "__len__") else float(T_val)
            z_scaled = Z_oof / T
            z_shift = z_scaled - np.max(z_scaled, axis=1, keepdims=True)
            exp_z = np.exp(z_shift)
            probs = exp_z / np.sum(exp_z, axis=1, keepdims=True)
            probs = np.clip(probs, 1e-15, 1.0)
            return -float(np.mean(np.log(probs[np.arange(n_samples), y])))

        res = minimize(nll_objective, x0=[1.0], bounds=[self.bounds], method="L-BFGS-B")
        self.temperature_ = float(res.x[0]) if res.success else 1.0
        return self

    def predict_proba(self, Z: np.ndarray) -> np.ndarray:
        T = self.temperature_
        z_scaled = Z / T
        z_shift = z_scaled - np.max(z_scaled, axis=1, keepdims=True)
        exp_z = np.exp(z_shift)
        probs = exp_z / np.sum(exp_z, axis=1, keepdims=True)
        probs = np.clip(probs, 1e-15, 1.0)
        probs /= np.sum(probs, axis=1, keepdims=True)
        return probs

    def predict(self, Z: np.ndarray) -> np.ndarray:
        return np.argmax(Z, axis=1)


class MulticlassPlattCalibrator:
    """
    Multiclass Platt calibrator (vector scaling) using multinomial logistic regression.
    
    Learns an affine transformation followed by softmax:
        p(y = c | z) = softmax(W z + b)
    from out-of-fold decision scores z in R^C to target labels y in {0, ..., C-1}.
    """
    
    def __init__(self, C_reg: float = 1.0, max_iter: int = 1000):
        self.C_reg = C_reg
        self.max_iter = max_iter
        self.calibrator_ = None
        self.classes_ = None
        
    def fit(self, Z_oof: np.ndarray, y: np.ndarray) -> "MulticlassPlattCalibrator":
        self.classes_ = np.sort(np.unique(y))
        self.calibrator_ = LogisticRegression(
            C=self.C_reg,
            solver="lbfgs",
            max_iter=self.max_iter,
            random_state=42,
        )
        self.calibrator_.fit(Z_oof, y)
        return self
        
    def predict_proba(self, Z: np.ndarray) -> np.ndarray:
        if self.calibrator_ is None:
            raise RuntimeError("Calibrator is not fitted yet!")
        probs = self.calibrator_.predict_proba(Z)
        probs = np.clip(probs, 1e-15, 1.0)
        probs /= np.sum(probs, axis=1, keepdims=True)
        return probs
        
    def predict(self, Z: np.ndarray) -> np.ndarray:
        probs = self.predict_proba(Z)
        return np.argmax(probs, axis=1)


class UncalibratedSoftmaxCalibrator:
    """
    Reference baseline calibrator: applies raw temperature-1 softmax to decision scores.
        p(y = c | z) = exp(z_c) / sum_j exp(z_j)
    """
    def __init__(self):
        self.classes_ = None
        
    def fit(self, Z_oof: np.ndarray, y: np.ndarray) -> "UncalibratedSoftmaxCalibrator":
        self.classes_ = np.sort(np.unique(y))
        return self
        
    def predict_proba(self, Z: np.ndarray) -> np.ndarray:
        z_shifted = Z - np.max(Z, axis=1, keepdims=True)
        exp_z = np.exp(z_shifted)
        probs = exp_z / np.sum(exp_z, axis=1, keepdims=True)
        probs = np.clip(probs, 1e-15, 1.0)
        probs /= np.sum(probs, axis=1, keepdims=True)
        return probs
        
    def predict(self, Z: np.ndarray) -> np.ndarray:
        return np.argmax(Z, axis=1)
